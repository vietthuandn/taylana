-- ---------- 1. Cài đặt thanh toán: bảng site_settings, key "payment" ----------
-- Ai cũng đọc được (đều là thông tin công khai để hiện QR), chỉ admin sửa được (policy có sẵn của site_settings).
insert into public.site_settings (key, value) values ('payment', jsonb_build_object(
  'enabled', false,
  'bank_bin', '970436', 'bank_name', 'Vietcombank',
  'account_no', '', 'account_name', '',
  'prefix', 'TAYLANA',
  'mode', 'full',            -- 'full' = thu 100%, 'deposit' = đặt cọc
  'deposit_percent', 50,
  'deadline_hours', 24,
  'note', 'Tiệm sẽ xác nhận trong vòng 30 phút giờ hành chính.'
)) on conflict (key) do nothing;

-- ---------- 2. Cột mới cho đơn hàng ----------
alter table public.orders add column if not exists order_no bigint generated by default as identity (start with 1001);
create unique index if not exists orders_order_no_key on public.orders (order_no);
alter table public.orders add column if not exists payment_code text;           -- ví dụ TAYLANA1024
create unique index if not exists orders_payment_code_key on public.orders (payment_code);
alter table public.orders add column if not exists amount_due integer not null default 0;   -- số tiền cần chuyển (100% hoặc tiền cọc)
alter table public.orders add column if not exists paid_amount integer not null default 0;  -- tổng tiền đã nhận
alter table public.orders add column if not exists payment_status text not null default 'unpaid';
alter table public.orders drop constraint if exists orders_payment_status_check;
alter table public.orders add constraint orders_payment_status_check
  check (payment_status in ('unpaid', 'pending', 'deposited', 'paid', 'expired', 'cancelled'));
alter table public.orders add column if not exists payment_deadline timestamptz;
alter table public.orders add column if not exists payment_claimed_at timestamptz;    -- lúc khách bấm "Tôi đã chuyển khoản"
alter table public.orders add column if not exists payment_confirmed_at timestamptz;
alter table public.orders add column if not exists payment_confirmed_by text;         -- email admin
alter table public.orders add column if not exists payment_note text not null default '';
alter table public.orders add column if not exists payment_log jsonb not null default '[]'::jsonb; -- lịch sử: ai, lúc nào, làm gì
create index if not exists orders_payment_status_idx on public.orders (payment_status, created_at desc);

-- Tiền tố an toàn cho app ngân hàng: chỉ chữ HOA không dấu + số
create or replace function public.payment_prefix()
returns text language sql stable security definer set search_path = public as $$
  select coalesce(nullif(regexp_replace(upper(coalesce(
    (select value->>'prefix' from public.site_settings where key = 'payment'), 'TAYLANA')), '[^A-Z0-9]', '', 'g'), ''), 'TAYLANA');
$$;

-- Số tiền cần chuyển theo cài đặt (100% hoặc cọc X%), làm tròn lên nghìn đồng
create or replace function public.payment_amount_for(p_total integer)
returns integer language plpgsql stable security definer set search_path = public as $$
declare
  v jsonb := (select value from public.site_settings where key = 'payment');
  pct numeric;
begin
  if coalesce(v->>'mode', 'full') = 'deposit' then
    pct := greatest(1, least(100, coalesce((v->>'deposit_percent')::numeric, 50)));
    return (ceil(p_total * pct / 100 / 1000.0) * 1000)::int;
  end if;
  return p_total;
end $$;

-- Đơn mới: tự gán mã thanh toán, số tiền cần chuyển, hạn thanh toán.
-- Tổng tiền (total) do create_order tính ở SERVER theo giá trong database.
create or replace function public.orders_payment_defaults()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_hours numeric := coalesce((select (value->>'deadline_hours')::numeric from public.site_settings where key = 'payment'), 24);
begin
  if new.order_no is null then new.order_no := nextval(pg_get_serial_sequence('public.orders', 'order_no')); end if;
  new.payment_code := public.payment_prefix() || new.order_no;
  new.amount_due := public.payment_amount_for(new.total);
  new.payment_status := 'unpaid';
  new.payment_deadline := now() + make_interval(secs => greatest(1, v_hours) * 3600);
  return new;
end $$;
drop trigger if exists orders_payment_defaults on public.orders;
create trigger orders_payment_defaults before insert on public.orders
  for each row execute function public.orders_payment_defaults();

-- Admin sửa tổng tiền khi đơn chưa thanh toán → tính lại số tiền cần chuyển
create or replace function public.orders_payment_on_update()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.total is distinct from old.total and new.payment_status in ('unpaid', 'pending', 'expired') then
    new.amount_due := public.payment_amount_for(new.total);
  end if;
  return new;
end $$;
drop trigger if exists orders_payment_on_update on public.orders;
create trigger orders_payment_on_update before update on public.orders
  for each row execute function public.orders_payment_on_update();

-- Đơn cũ (trước khi có thanh toán): gán mã + số tiền
update public.orders
set payment_code = public.payment_prefix() || order_no,
    amount_due = case when amount_due = 0 then total else amount_due end
where payment_code is null;

-- ---------- 3. Bảng payments: từng giao dịch đã nhận ----------
create table if not exists public.payments (
  id           uuid primary key default gen_random_uuid(),
  order_id     uuid not null references public.orders(id) on delete cascade,
  amount       integer not null check (amount >= 0),
  source       text not null default 'manual' check (source in ('manual', 'sepay', 'payos')),
  bank_txn_id  text,                         -- mã giao dịch ngân hàng (Mức 2)
  paid_at      timestamptz not null default now(),
  note         text not null default '',
  created_by   text,                         -- email admin (manual) hoặc tên dịch vụ
  raw          jsonb,                        -- dữ liệu gốc từ webhook (Mức 2)
  created_at   timestamptz not null default now()
);
create index if not exists payments_order_idx on public.payments (order_id, created_at desc);
create unique index if not exists payments_bank_txn_key on public.payments (source, bank_txn_id) where bank_txn_id is not null;

alter table public.payments enable row level security;
grant select, insert, update, delete on public.payments to authenticated;
drop policy if exists "payments: admin toàn quyền" on public.payments;
create policy "payments: admin toàn quyền" on public.payments
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- ---------- 4. Hàm cho khách (chỉ qua mã đơn, không lộ tên/SĐT/địa chỉ) ----------
-- Xem thông tin thanh toán của 1 đơn. Quá hạn mà chưa thanh toán → tự chuyển "Hết hạn".
drop function if exists public.get_order_payment(text);
create or replace function public.get_order_payment(p_code text)
returns table (order_code text, payment_code text, total integer, amount_due integer, paid_amount integer,
               payment_status text, payment_deadline timestamptz, payment_claimed_at timestamptz, created_at timestamptz)
language plpgsql security definer set search_path = public as $$
begin
  update public.orders o set payment_status = 'expired'
  where upper(o.code) = upper(trim(p_code)) and o.payment_status = 'unpaid'
    and o.payment_deadline is not null and o.payment_deadline < now();
  return query
    select o.code, o.payment_code, o.total, o.amount_due, o.paid_amount, o.payment_status,
           o.payment_deadline, o.payment_claimed_at, o.created_at
    from public.orders o where upper(o.code) = upper(trim(p_code)) limit 1;
end $$;

-- Khách bấm "Tôi đã chuyển khoản": CHỈ đổi "Chưa thanh toán" → "Chờ xác nhận" (không đánh dấu đã trả).
create or replace function public.claim_order_payment(p_code text)
returns text language plpgsql security definer set search_path = public as $$
declare v_status text;
begin
  update public.orders o
  set payment_status = 'pending', payment_claimed_at = now(),
      payment_log = o.payment_log || jsonb_build_object('at', now(), 'by', 'khách', 'action', 'claimed')
  where upper(o.code) = upper(trim(p_code)) and o.payment_status = 'unpaid'
    and (o.payment_deadline is null or o.payment_deadline >= now())
  returning o.payment_status into v_status;
  if v_status is null then
    select o.payment_status into v_status from public.orders o where upper(o.code) = upper(trim(p_code));
  end if;
  return v_status;
end $$;

-- ---------- 5. Hàm cho admin ----------
-- Xác nhận đã nhận tiền: tạo 1 dòng payments (manual) + cập nhật trạng thái đơn + ghi lịch sử
create or replace function public.admin_confirm_payment(p_order_id uuid, p_status text, p_amount integer, p_note text default '')
returns void language plpgsql security definer set search_path = public as $$
declare v_email text := coalesce(auth.jwt()->>'email', auth.uid()::text);
begin
  if not public.is_admin() then raise exception 'Chỉ admin được xác nhận thanh toán'; end if;
  if p_status not in ('deposited', 'paid') then raise exception 'Trạng thái không hợp lệ'; end if;
  if coalesce(p_amount, 0) < 0 then raise exception 'Số tiền không hợp lệ'; end if;
  insert into public.payments (order_id, amount, source, note, created_by)
  values (p_order_id, coalesce(p_amount, 0), 'manual', coalesce(p_note, ''), v_email);
  update public.orders
  set payment_status = p_status,
      paid_amount = paid_amount + coalesce(p_amount, 0),
      payment_confirmed_at = now(), payment_confirmed_by = v_email,
      payment_note = coalesce(p_note, ''),
      payment_log = payment_log || jsonb_build_object('at', now(), 'by', v_email, 'action', p_status,
                                                      'amount', coalesce(p_amount, 0), 'note', coalesce(p_note, ''))
  where id = p_order_id;
end $$;

-- Huỷ thanh toán
create or replace function public.admin_cancel_payment(p_order_id uuid, p_note text default '')
returns void language plpgsql security definer set search_path = public as $$
declare v_email text := coalesce(auth.jwt()->>'email', auth.uid()::text);
begin
  if not public.is_admin() then raise exception 'Chỉ admin được huỷ thanh toán'; end if;
  update public.orders
  set payment_status = 'cancelled', payment_note = coalesce(p_note, ''),
      payment_log = payment_log || jsonb_build_object('at', now(), 'by', v_email, 'action', 'cancelled', 'note', coalesce(p_note, ''))
  where id = p_order_id;
end $$;

-- Mở lại thanh toán (đưa về "Chưa thanh toán", gia hạn theo cài đặt)
create or replace function public.admin_reopen_payment(p_order_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_email text := coalesce(auth.jwt()->>'email', auth.uid()::text);
  v_hours numeric := coalesce((select (value->>'deadline_hours')::numeric from public.site_settings where key = 'payment'), 24);
begin
  if not public.is_admin() then raise exception 'Chỉ admin được thao tác'; end if;
  update public.orders
  set payment_status = 'unpaid', payment_deadline = now() + make_interval(secs => greatest(1, v_hours) * 3600),
      payment_log = payment_log || jsonb_build_object('at', now(), 'by', v_email, 'action', 'reopened')
  where id = p_order_id;
end $$;

revoke all on function public.get_order_payment(text) from public;
revoke all on function public.claim_order_payment(text) from public;
revoke all on function public.admin_confirm_payment(uuid, text, integer, text) from public;
revoke all on function public.admin_cancel_payment(uuid, text) from public;
revoke all on function public.admin_reopen_payment(uuid) from public;
grant execute on function public.get_order_payment(text) to anon, authenticated;
grant execute on function public.claim_order_payment(text) to anon, authenticated;
grant execute on function public.admin_confirm_payment(uuid, text, integer, text) to authenticated;
grant execute on function public.admin_cancel_payment(uuid, text) to authenticated;
grant execute on function public.admin_reopen_payment(uuid) to authenticated;
revoke all on function public.payment_prefix() from public;
revoke all on function public.payment_amount_for(integer) from public;
